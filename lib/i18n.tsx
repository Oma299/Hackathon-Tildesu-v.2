interface LangContextValue {
  lang: Lang
  t: (key: keyof typeof dict | string) => string
}

const LangContext = createContext<LangContextValue | null>(null)

// Сайт зафиксирован на русском языке. Переключатель языков удален.
const FIXED_LANG: Lang = "RU"

export function LanguageProvider({ children }: { children: ReactNode }) {
  const t = (key: string) => dict[key]?.[FIXED_LANG] ?? key

  return <LangContext.Provider value={{ lang: FIXED_LANG, t }}>{children}</LangContext.Provider>
}

export function useLanguage() {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider")
  return ctx
}
